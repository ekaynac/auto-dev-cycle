// Command vocabgen writes the reason and hold constants of internal/vocab
// from the embedded registries (make gen). Code names reasons only through
// these constants; `adc dev vocab check` refuses raw literals.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"

	"github.com/ekaynac/auto-dev-cycle/internal/vocab"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: vocabgen <output file>")
		os.Exit(64)
	}
	if err := run(os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, "vocabgen:", err)
		os.Exit(1)
	}
}

func run(out string) error {
	reg, err := vocab.Load()
	if err != nil {
		return err
	}
	reasonNames, err := vocab.GoNames(sortedKeys(reg.Reasons))
	if err != nil {
		return fmt.Errorf("reasons: %w", err)
	}
	holdNames, err := vocab.GoNames(sortedKeys(reg.Holds))
	if err != nil {
		return fmt.Errorf("holds: %w", err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/vocabgen from schemas/vocab. DO NOT EDIT.\n\n// SPDX-License-Identifier: Apache-2.0\n\npackage vocab\n\nimport \"github.com/ekaynac/auto-dev-cycle/gen/go/types\"\n\n")
	b.WriteString("// Registered reason codes (schemas/vocab/reasons.yaml). The values are\n// immutable; adc dev vocab check refuses writing to them.\nvar (\n")
	for _, code := range sortedKeys(reg.Reasons) {
		x := reg.Reasons[code]
		fmt.Fprintf(&b, "\t// Reason%s: %s\n\tReason%s = types.ReasonCodeOf(%q)\n", reasonNames[code], x.Description, reasonNames[code], code)
	}
	b.WriteString(")\n\n// Registered hold reasons (schemas/vocab/holds.yaml).\nconst (\n")
	for _, h := range sortedKeys(reg.Holds) {
		fmt.Fprintf(&b, "\tHold%s = %q\n", holdNames[h], h)
	}
	b.WriteString(")\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
