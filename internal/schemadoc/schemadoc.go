// Package schemadoc renders docs/reference/schemas from the embedded schema
// files (docs/design/m0/00 "M0 exit check": make schema-docs): one page per
// schema file and an index. Every object with fields gets a section (its
// definitions, and nested inline objects under their path); every type
// shows its constraints, those beside a $ref included. The pages describe
// the schemas; they never replace them.
package schemadoc

import (
	"encoding/json"
	"fmt"
	"io/fs"
	"path"
	"regexp"
	"strings"
	"unicode"

	"go.yaml.in/yaml/v3"
)

// Page is one generated file: its name under docs/reference/schemas and
// its content.
type Page struct {
	Name, Content string
}

// PageName is the page of a schema file ("records/lease.json" →
// "records-lease.md").
func PageName(file string) string {
	return strings.ReplaceAll(strings.TrimSuffix(file, ".json"), "/", "-") + ".md"
}

const banner = "<!-- Generated by tools/schemadoc (make gen); do not edit. -->\n\n"

// Slug is GitHub's heading anchor: lowercase, letters, digits, spaces,
// hyphens and underscores kept, spaces turned into hyphens.
func Slug(heading string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(heading) {
		switch {
		case r == ' ':
			b.WriteRune('-')
		case r == '-' || r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r):
			b.WriteRune(r)
		}
	}
	return b.String()
}

// Render renders every schema file in files (sorted) and an index.
func Render(fsys fs.FS, files []string) ([]Page, error) {
	var pages []Page
	var index strings.Builder
	index.WriteString(banner + "# Schema reference\n\nOne page per schema file under `schemas/`. The schemas are the contract; these pages only describe them.\n\n| Schema | Title |\n|---|---|\n")
	for _, f := range files {
		b, err := fs.ReadFile(fsys, f)
		if err != nil {
			return nil, err
		}
		var doc yaml.Node
		if err := yaml.Unmarshal(b, &doc); err != nil {
			return nil, fmt.Errorf("schemadoc: %s: %w", f, err)
		}
		root := doc.Content[0]
		title := scalar(get(root, "title"))
		if title == "" {
			title = f
		}
		r := &renderer{file: f}
		fmt.Fprintf(&r.b, "%s# %s\n\n`schemas/%s`\n\n", banner, title, f)
		r.describe(root)
		if one := get(root, "oneOf"); one != nil && get(root, "properties") == nil {
			fmt.Fprintf(&r.b, "A document is one of: %s.\n\n", r.alternatives(one, ""))
		}
		r.object(root, "", "##")
		if defs := get(root, "$defs"); defs != nil {
			r.b.WriteString("## Definitions\n\n")
			for i := 0; i+1 < len(defs.Content); i += 2 {
				name, def := defs.Content[i].Value, defs.Content[i+1]
				fmt.Fprintf(&r.b, "### %s\n\n", name)
				r.describe(def)
				if get(def, "properties") != nil {
					r.object(def, name, "####")
					continue
				}
				fmt.Fprintf(&r.b, "Type: %s\n\n", r.typeOf(def, name))
				for _, inner := range inlineObjects(def, name) {
					r.object(inner[1].(*yaml.Node), inner[0].(string), "####")
				}
			}
		}
		pages = append(pages, Page{PageName(f), strings.TrimRight(r.b.String(), "\n") + "\n"})
		fmt.Fprintf(&index, "| [`%s`](%s) | %s |\n", f, PageName(f), cell(title))
	}
	return append(pages, Page{"README.md", index.String()}), nil
}

type renderer struct {
	file string
	b    strings.Builder
}

func (r *renderer) describe(n *yaml.Node) {
	if d := scalar(get(n, "description")); d != "" {
		r.b.WriteString(text(d) + "\n\n")
	}
}

// object writes n's fields table, its openness and its conditional rules,
// then a section for each nested inline object, named by its path.
func (r *renderer) object(n *yaml.Node, at, level string) {
	props := get(n, "properties")
	if props == nil {
		return
	}
	required := map[string]bool{}
	if req := get(n, "required"); req != nil {
		for _, c := range req.Content {
			required[c.Value] = true
		}
	}
	fmt.Fprintf(&r.b, "%s Fields of %s\n\n", level, label(at))
	if len(props.Content) == 0 {
		r.b.WriteString("No fields are defined.\n\n")
	} else {
		r.b.WriteString("| Field | Required | Type | Description |\n|---|---|---|---|\n")
	}
	var nested [][2]any // path, schema
	for i := 0; i+1 < len(props.Content); i += 2 {
		name, p := props.Content[i].Value, props.Content[i+1]
		req := ""
		if required[name] {
			req = "yes"
		}
		sub := join(at, name)
		fmt.Fprintf(&r.b, "| `%s` | %s | %s | %s |\n", name, req, cell(r.typeOf(p, sub)), cell(text(scalar(get(p, "description")))))
		for _, inner := range inlineObjects(p, sub) {
			nested = append(nested, inner)
		}
	}
	if len(props.Content) > 0 {
		r.b.WriteString("\n")
	}
	if extra := get(n, "additionalProperties"); extra != nil && extra.Value == "false" {
		r.b.WriteString("No other fields are allowed.\n\n")
	} else {
		r.b.WriteString("Other fields are allowed.\n\n")
	}
	r.rules(n)
	for _, inner := range nested {
		r.object(inner[1].(*yaml.Node), inner[0].(string), level)
	}
}

// rules lists n's conditional rules (if/then, at the top or in allOf), with
// their descriptions.
func (r *renderer) rules(n *yaml.Node) {
	var conds []*yaml.Node
	if get(n, "if") != nil {
		conds = append(conds, n)
	}
	if all := get(n, "allOf"); all != nil {
		for _, c := range all.Content {
			if get(c, "if") != nil {
				conds = append(conds, c)
			}
		}
	}
	if len(conds) == 0 {
		return
	}
	fmt.Fprintf(&r.b, "Conditional rules (%d, `if`/`then`/`else` in the schema):\n\n", len(conds))
	for _, c := range conds {
		line := "when " + r.fieldsOf(get(c, "if")) + ", then " + r.fieldsOf(get(c, "then"))
		if e := get(c, "else"); e != nil {
			line += "; otherwise " + r.fieldsOf(e)
		}
		if d := scalar(get(c, "description")); d != "" && c != n {
			line = text(d) + " (" + line + ")"
		}
		r.b.WriteString("- " + line + "\n")
	}
	r.b.WriteString("\n")
}

// fieldsOf names the fields a branch of a rule constrains, with the
// constraint, and those it requires.
func (r *renderer) fieldsOf(b *yaml.Node) string {
	var out []string
	if props := get(b, "properties"); props != nil {
		for i := 0; i+1 < len(props.Content); i += 2 {
			out = append(out, "`"+props.Content[i].Value+"` "+r.typeOf(props.Content[i+1], ""))
		}
	}
	if req := get(b, "required"); req != nil {
		for _, c := range req.Content {
			out = append(out, "`"+c.Value+"` required")
		}
	}
	if len(out) == 0 {
		return "(see the schema)"
	}
	return strings.Join(out, ", ")
}

// inlineObjects finds the objects with fields defined inline in p (directly,
// as array items, or as oneOf branches), each with its path.
func inlineObjects(p *yaml.Node, at string) [][2]any {
	switch {
	case p == nil || get(p, "$ref") != nil:
		return nil
	case get(p, "properties") != nil:
		return [][2]any{{at, p}}
	case get(p, "items") != nil:
		return inlineObjects(get(p, "items"), at+"[]")
	case get(p, "additionalProperties") != nil && get(p, "additionalProperties").Kind == yaml.MappingNode:
		return inlineObjects(get(p, "additionalProperties"), at+"{}")
	case get(p, "oneOf") != nil:
		var out [][2]any
		for _, b := range get(p, "oneOf").Content {
			out = append(out, inlineObjects(b, at)...)
		}
		return out
	}
	return nil
}

// typeOf renders a schema's type in one line; at is its path, for links to
// nested object sections.
func (r *renderer) typeOf(n *yaml.Node, at string) string {
	if n == nil {
		return "any"
	}
	base := ""
	switch {
	case scalar(get(n, "$ref")) != "":
		base = r.refLink(scalar(get(n, "$ref")))
	case get(n, "const") != nil:
		base = "`" + literal(get(n, "const")) + "`"
	case get(n, "enum") != nil:
		var vs []string
		for _, v := range get(n, "enum").Content {
			vs = append(vs, "`"+literal(v)+"`")
		}
		base = "one of " + strings.Join(vs, ", ")
	case get(n, "oneOf") != nil:
		base = r.alternatives(get(n, "oneOf"), at)
	case get(n, "properties") != nil:
		base = fmt.Sprintf("object ([fields](#%s))", Slug("Fields of "+label(at)))
	default:
		switch t := scalar(get(n, "type")); t {
		case "array":
			base = "array of " + r.typeOf(get(n, "items"), at+"[]")
		case "object":
			base = "object"
			if v := get(n, "additionalProperties"); v != nil && v.Kind == yaml.MappingNode {
				key := "string"
				if k := get(n, "propertyNames"); k != nil {
					key = r.typeOf(k, at)
				}
				base = "map of " + key + " to " + r.typeOf(v, at+"{}")
				break
			}
			if get(n, "x-adc-open-payload") != nil {
				base = "object (open payload)"
			}
		case "":
			base = "any"
		default:
			base = t
		}
	}
	if lim := limits(n); lim != "" {
		return base + " (" + lim + ")"
	}
	return base
}

func (r *renderer) alternatives(one *yaml.Node, at string) string {
	var vs []string
	for _, v := range one.Content {
		vs = append(vs, r.typeOf(v, at))
	}
	return strings.Join(vs, " or ")
}

// limits lists the constraints a schema node carries itself.
func limits(n *yaml.Node) string {
	var out []string
	for _, k := range []string{"pattern", "format", "minLength", "maxLength", "minimum", "maximum", "minItems", "maxItems", "minProperties", "maxProperties"} {
		if v := scalar(get(n, k)); v != "" {
			out = append(out, k+" `"+v+"`")
		}
	}
	if u := get(n, "uniqueItems"); u != nil && u.Value == "true" {
		out = append(out, "unique items")
	}
	if c := get(n, "not"); c != nil {
		if k := get(c, "const"); k != nil && len(c.Content) == 2 {
			out = append(out, "not `"+literal(k)+"`")
		} else {
			out = append(out, "with a `not` constraint")
		}
	}
	return strings.Join(out, ", ")
}

// refLink links a $ref to the definition's page and anchor.
func (r *renderer) refLink(ref string) string {
	target, frag, _ := strings.Cut(ref, "#")
	page := ""
	if target != "" {
		page = PageName(path.Join(path.Dir(r.file), target))
	}
	if frag == "" || !strings.HasPrefix(frag, "/$defs/") {
		return fmt.Sprintf("[%s](%s)", strings.TrimSuffix(path.Base(target), ".json"), page)
	}
	// A ref into a definition (…/$defs/Name/…) links to that definition.
	name := strings.TrimPrefix(frag, "/$defs/")
	def, _, _ := strings.Cut(name, "/")
	return fmt.Sprintf("[%s](%s#%s)", name, page, Slug(def))
}

func label(at string) string {
	if at == "" {
		return "the document"
	}
	return at
}

func join(at, name string) string {
	if at == "" {
		return name
	}
	return at + "." + name
}

// literal is a value as JSON: a scalar's text, or a list or map encoded.
func literal(n *yaml.Node) string {
	if n.Kind == yaml.ScalarNode {
		return n.Value
	}
	var v any
	if err := n.Decode(&v); err != nil {
		return "(see the schema)"
	}
	b, err := json.Marshal(v)
	if err != nil {
		return "(see the schema)"
	}
	return string(b)
}

func get(n *yaml.Node, key string) *yaml.Node {
	if n == nil || n.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			return n.Content[i+1]
		}
	}
	return nil
}

func scalar(n *yaml.Node) string {
	if n == nil || n.Kind != yaml.ScalarNode {
		return ""
	}
	return n.Value
}

var angle = regexp.MustCompile(`[<>]`)

// text keeps prose from being read as HTML.
func text(s string) string {
	return angle.ReplaceAllStringFunc(s, func(m string) string {
		if m == "<" {
			return "&lt;"
		}
		return "&gt;"
	})
}

// cell makes text safe inside a Markdown table cell.
func cell(s string) string {
	return strings.NewReplacer("|", "\\|", "\n", " ").Replace(s)
}
