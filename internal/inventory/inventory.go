// Package inventory counts the rows of the invariant-enforcement inventory
// (docs/design/m1/01-invariant-inventory.md) by status, and writes its
// count line from them (make gen, tools/inventorygen). The line is never
// edited by hand: a branch that changes a row regenerates it, so two
// branches never conflict over figures.
package inventory

import (
	"bufio"
	"bytes"
	"errors"
	"fmt"
	"strings"
)

// Path is the inventory, from the repository root.
const Path = "docs/design/m1/01-invariant-inventory.md"

// The statuses a row may hold (the inventory's "How to read this").
const (
	Kept       = "kept"
	Gap        = "GAP"
	KeptAndGap = "kept + GAP"
	NA         = "n/a"
)

// The markers around the generated count.
const (
	Begin = "<!-- count: generated by make gen (tools/inventorygen) from the tables above; do not edit -->"
	End   = "<!-- end count -->"
)

// Counts are an inventory's invariants and its rows by status.
type Counts struct {
	Invariants int
	ByStatus   map[string]int
}

// Rows is every row.
func (c Counts) Rows() int {
	n := 0
	for _, v := range c.ByStatus {
		n += v
	}
	return n
}

// Line is the count's text.
func (c Counts) Line() string {
	return fmt.Sprintf("%d rows across %d invariants. **%d rows have a gap**: %d are GAP and %d are kept + GAP. %d are kept and %d are n/a.",
		c.Rows(), c.Invariants, c.ByStatus[Gap]+c.ByStatus[KeptAndGap], c.ByStatus[Gap], c.ByStatus[KeptAndGap], c.ByStatus[Kept], c.ByStatus[NA])
}

// Count counts doc's invariants (its "## I<n>." sections) and the rows of
// their tables by status (the third column). A row of another status is an
// error.
func Count(doc []byte) (Counts, error) {
	c := Counts{ByStatus: map[string]int{}}
	in := false
	sc := bufio.NewScanner(bytes.NewReader(doc))
	sc.Buffer(nil, 1<<20)
	for sc.Scan() {
		l := sc.Text()
		if strings.HasPrefix(l, "## ") {
			in = strings.HasPrefix(l, "## I") && strings.Contains(l, ".")
			if in {
				c.Invariants++
			}
			continue
		}
		if !in || !strings.HasPrefix(l, "| ") || strings.HasPrefix(l, "| Check") {
			continue
		}
		cells := strings.Split(strings.Trim(l, "|"), "|")
		if len(cells) < 4 {
			continue
		}
		switch s := strings.TrimSpace(cells[2]); s {
		case Kept, Gap, KeptAndGap, NA:
			c.ByStatus[s]++
		default:
			return c, fmt.Errorf("inventory: a row's status is %q: %s", s, l)
		}
	}
	return c, sc.Err()
}

// Rewrite is doc with the text between its markers set to its count line.
func Rewrite(doc []byte) ([]byte, error) {
	c, err := Count(doc)
	if err != nil {
		return nil, err
	}
	s := string(doc)
	b, e := strings.Index(s, Begin+"\n"), strings.Index(s, "\n"+End)
	if b < 0 || e < b || strings.Count(s, Begin) != 1 || strings.Count(s, End) != 1 {
		return nil, errors.New("inventory: the count markers are missing, repeated or out of order")
	}
	return []byte(s[:b+len(Begin)+1] + c.Line() + s[e:]), nil
}
