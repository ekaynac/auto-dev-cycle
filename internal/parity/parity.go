// Package parity joins the action registry, the daemon's wiring, the CLI
// and the API description into one matrix (14 PR 11, 08 "Dashboard
// parity"): every registered action is wired, deferred or unregistered
// (14 D1), and every action and read has its endpoint and its CLI command.
// The routes the daemon serves (daemon.Routes) are checked against the
// generated API description, of which gen-check pins the committed copy.
// Its tests fail on a mismatch; tools/paritygen renders the matrix as
// docs/reference/action-matrix.md (make gen).
package parity

import (
	"bytes"
	"fmt"
	"maps"
	"slices"

	"github.com/ekaynac/auto-dev-cycle/internal/api"
	"github.com/ekaynac/auto-dev-cycle/internal/apidoc"
	"github.com/ekaynac/auto-dev-cycle/internal/cli"
	"github.com/ekaynac/auto-dev-cycle/internal/daemon"
	"github.com/ekaynac/auto-dev-cycle/internal/vocab"
)

// Action is a registered action's row: its class, its endpoint and its CLI
// command.
type Action struct {
	daemon.Row
	Endpoint, CLI string
}

// Read is a read: its endpoint and its CLI command.
type Read struct {
	Resource, Endpoint, CLI string
}

// readCommands are the reads' CLI commands, by resource. A read without
// one fails the parity test and is refused by Markdown.
var readCommands = cli.ReadCommands()

// UndocumentedRoutes are the routes the daemon serves that the API
// description does not carry, and why; documenting one is a contract PR.
var UndocumentedRoutes = map[string]string{
	"GET /v1/version": "the daemon's build (api.Version); not yet in schemas/openapi.yaml, which is a contract change",
}

// Dashboard is the milestone of every action's dashboard control (08
// "Dashboard parity", the dashboard side stubbed until M5).
const Dashboard = "M5"

// Actions is the action matrix, sorted by action.
func Actions(reg *vocab.Registry) ([]Action, error) {
	rows, err := daemon.Matrix(reg)
	if err != nil {
		return nil, err
	}
	cmds := cli.Commands()
	out := make([]Action, 0, len(rows))
	for _, r := range rows {
		out = append(out, Action{Row: r, Endpoint: "POST " + apidoc.CommandPath(r.Action), CLI: cmds[r.Action]})
	}
	return out, nil
}

// Reads are the reads the controller serves, sorted by resource: the event
// stream, whoami and each registered resource.
func Reads() []Read {
	paths := map[string]string{"events": api.EventsPath, "whoami": api.WhoamiPath}
	for name := range api.Registered() {
		paths[name] = "/v1/" + name
	}
	var out []Read
	for _, name := range slices.Sorted(maps.Keys(paths)) {
		out = append(out, Read{Resource: name, Endpoint: "GET " + paths[name], CLI: readCommands[name]})
	}
	return out
}

// Bootstrap is the one command that is neither an action nor a read.
var Bootstrap = Read{Resource: "bootstrap", Endpoint: "POST " + apidoc.BootstrapPath, CLI: "adc admin bootstrap"}

// Blobs are the upload endpoints (00-slice-plan P2) and the sandbox probe
// (P9), neither actions nor reads.
var Blobs = []Read{{Resource: "blob upload", Endpoint: "POST " + api.BlobsPath, CLI: "adc blob put"},
	{Resource: api.BlobUploads, Endpoint: "GET " + api.BlobsPath, CLI: "adc dev blob uploads"},
	{Resource: "sandbox probe", Endpoint: "POST " + api.SandboxProbePath, CLI: "adc dev sandbox probe"}}

// Markdown renders the matrix; the same inputs give the same bytes. A read
// without a CLI command is refused.
func Markdown(actions []Action, reads []Read) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("<!-- SPDX-License-Identifier: Apache-2.0 -->\n<!-- Generated by tools/paritygen (make gen); do not edit. -->\n\n")
	b.WriteString("# Action and read matrix\n\n")
	b.WriteString("How this build answers each registered action (`schemas/vocab/actions.yaml`, 14 D1), and the endpoint and CLI\n")
	b.WriteString("command of every action and read (08). `internal/parity` checks it against the daemon's wiring and routes, the CLI\n")
	b.WriteString("and the generated API description (gen-check pins the committed `schemas/openapi.yaml`).\n\n")
	b.WriteString("- **wired**: a handler, and a logic or an issuer (a credential-issuing request layer); its handler decides.\n")
	b.WriteString("- **deferred**: answered `could_not_run/action_deferred`, with nothing submitted; owned by the milestone shown,\n")
	b.WriteString("  or `unassigned` where no plan or design document names one.\n")
	b.WriteString("- **unregistered** (deprecated): answered `failed/action_unregistered`.\n")
	fmt.Fprintf(&b, "- **Dashboard**: every action's dashboard control lands in %s (08 \"Dashboard parity\").\n\n", Dashboard)
	b.WriteString("## Actions\n\n| Action | Family | Class | Owner | Endpoint | CLI | Dashboard | Notes |\n|---|---|---|---|---|---|---|---|\n")
	for _, a := range actions {
		class, owner := string(a.Class), a.Owner.Milestone
		if a.Via != "" {
			class += " (" + a.Via + ")"
		}
		if a.Owner.Ref != "" {
			owner += " (" + a.Owner.Ref + ")"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | `%s` | `%s` | %s | %s |\n", a.Action, a.Family, class, owner, a.Endpoint, a.CLI, Dashboard, a.Note)
	}
	b.WriteString("\n## Reads and other endpoints\n\n| Resource | Endpoint | CLI |\n|---|---|---|\n")
	for _, r := range append(append(slices.Clone(reads), Bootstrap), Blobs...) {
		if r.CLI == "" {
			return nil, fmt.Errorf("parity: read %s has no CLI command", r.Resource)
		}
		fmt.Fprintf(&b, "| %s | `%s` | `%s` |\n", r.Resource, r.Endpoint, r.CLI)
	}
	b.WriteString("\n## Served, not in the API description\n\n| Route | Why |\n|---|---|\n")
	for _, route := range slices.Sorted(maps.Keys(UndocumentedRoutes)) {
		fmt.Fprintf(&b, "| `%s` | %s |\n", route, UndocumentedRoutes[route])
	}
	return b.Bytes(), nil
}
