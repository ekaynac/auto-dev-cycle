// Package apidoc generates schemas/openapi.yaml, the single API description
// (docs/design/m0/08 "Transport"), from the action registry: one command
// endpoint per action, POST /v1/commands/{action}, whose bodies are $refs
// into schemas/. Reads and the event stream join it with their handlers.
package apidoc

import (
	"bytes"
	"fmt"
	"maps"
	"slices"

	"go.yaml.in/yaml/v3"

	"github.com/ekaynac/auto-dev-cycle/gen/go/types"
)

// CommandPath is the endpoint of an action.
func CommandPath(action string) string { return "/v1/commands/" + action }

type ref struct {
	Ref string `yaml:"$ref"`
}

type media struct {
	Schema ref `yaml:"schema"`
}

type body struct {
	Description string           `yaml:"description,omitempty"`
	Required    bool             `yaml:"required,omitempty"`
	Content     map[string]media `yaml:"content,omitempty"`
}

type operation struct {
	OperationID string          `yaml:"operationId"`
	Tags        []string        `yaml:"tags"`
	Summary     string          `yaml:"summary"`
	Deprecated  bool            `yaml:"deprecated,omitempty"`
	Action      string          `yaml:"x-adc-action"`
	RequestBody body            `yaml:"requestBody"`
	Responses   map[string]body `yaml:"responses"`
}

type components struct {
	SecuritySchemes map[string]map[string]string `yaml:"securitySchemes"`
	Schemas         map[string]ref               `yaml:"schemas"`
}

type document struct {
	OpenAPI    string                          `yaml:"openapi"`
	Info       map[string]string               `yaml:"info"`
	Security   []map[string][]string           `yaml:"security"`
	Paths      map[string]map[string]operation `yaml:"paths"`
	Components components                      `yaml:"components"`
}

func jsonOf(schema string) map[string]media {
	return map[string]media{"application/json": {Schema: ref{"#/components/schemas/" + schema}}}
}

// Generate renders the document for the registry's actions; the same
// registry always gives the same bytes.
func Generate(actions map[string]types.Action) ([]byte, error) {
	d := document{
		OpenAPI: "3.1.0",
		Info: map[string]string{"title": "auto-dev-cycle controller API", "version": "v1",
			"description": "Generated by tools/apigen from schemas/vocab/actions.yaml (make gen); do not edit."},
		Security: []map[string][]string{{"bearer": {}}},
		Paths:    map[string]map[string]operation{},
		Components: components{
			SecuritySchemes: map[string]map[string]string{"bearer": {"type": "http", "scheme": "bearer"}},
			Schemas: map[string]ref{
				"CommandRequest":  {"api/command-request.json"},
				"CommandResponse": {"api/command-response.json"},
			},
		},
	}
	for _, name := range slices.Sorted(maps.Keys(actions)) {
		a := actions[name]
		if string(a.Action) != name {
			return nil, fmt.Errorf("apidoc: action %q registered as %q", a.Action, name)
		}
		d.Paths[CommandPath(name)] = map[string]operation{"post": {
			OperationID: "command." + name,
			Tags:        []string{string(a.Family)},
			Summary:     a.Description,
			Deprecated:  a.Deprecated != nil,
			Action:      name,
			RequestBody: body{Required: true, Content: jsonOf("CommandRequest")},
			Responses: map[string]body{
				"200": {Description: "The command was decided: applied, proposed or refused.", Content: jsonOf("CommandResponse")},
				"401": {Description: "No valid bearer token; nothing was decided."},
			},
		}}
	}
	var buf bytes.Buffer
	buf.WriteString("# SPDX-License-Identifier: Apache-2.0\n# Generated by tools/apigen (make gen); do not edit.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(d); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
